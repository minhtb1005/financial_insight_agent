"""Validate authored AI review notes and render separate, traceable track reports.

Raw live reports are immutable inputs. Independent human review stays pending.
No keyword-based semantic score is generated by this script.
"""

import argparse
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_dir", type=Path)
    parser.add_argument("--allow-partial", action="store_true")
    args = parser.parse_args()
    notes = [json.loads(line) for line in (args.run_dir / "review-notes.jsonl").read_text(
        encoding="utf-8").splitlines() if line.strip()]
    by_id = {note["id"]: note for note in notes}
    if len(by_id) != len(notes):
        raise ValueError("Duplicate review ID")
    known = set()
    for track in ("personal_finance", "market_literacy"):
        raw_path = args.run_dir / f"{track}.json"
        report = json.loads(raw_path.read_text(encoding="utf-8"))
        rows = []
        markdown = [f"# Đánh giá nội dung — {track}", "",
            "Người chấm: Codex AI; chưa phải đánh giá độc lập của con người. "
            "Điểm rubric: 0 sai/thiếu, 1 một phần, 2 đúng và rõ; N/A cho tiêu chí có điều kiện không liên quan câu hỏi. "
            "Không gộp điểm hai lộ trình. Đánh giá này áp dụng cho câu trả lời của lần chạy được liên kết, không chứng minh khả năng tổng quát.", ""]
        markdown.extend(["[Tổng hợp, phương pháp và việc cần sửa](../../../docs/diagnostics/curriculum-full-review-2026-10-22.md) · "
            "[Nguồn đối chiếu](sources.md)", ""])
        for case in report["cases"]:
            known.add(case["id"])
            note = by_id.get(case["id"])
            if note is None:
                if args.allow_partial:
                    continue
                raise ValueError(f"Missing review: {case['id']}")
            rubric = case["semantic_review"]["rubric"]
            if len(note["scores"]) != len(rubric) or any(
                s is not None and (type(s) is not int or s not in (0, 1, 2)) for s in note["scores"]
            ):
                raise ValueError(f"Invalid rubric scores: {case['id']}")
            if not note["notes"] or not note["evidence"]:
                raise ValueError(f"Missing evidence: {case['id']}")
            for quote in note["evidence"]:
                if quote not in case["answer"]:
                    raise ValueError(f"Evidence not verbatim in {case['id']}: {quote}")
            if note["verdict"] not in ("pass", "partial", "fail"):
                raise ValueError(f"Invalid verdict: {case['id']}")
            row = {**case, "ai_semantic_review": {
                **note, "reviewer": "Codex AI", "human_review_status": "pending",
                "answer_sha256": hashlib.sha256(case["answer"].encode()).hexdigest(),
                "rubric": [{"criterion": criterion, "score": score}
                    for criterion, score in zip(rubric, note["scores"], strict=True)],
            }}
            rows.append(row)
            markdown.extend([f"## {case['id']} — {note['verdict']}", "", case["query"], "",
                f"Kiểm tra tự động: {'đạt' if case['automated_pass'] else 'không đạt'}. "
                f"Thời gian: {case['latency_ms']/1000:.1f}s.", "", "| Tiêu chí | Điểm |",
                "|---|---|"])
            for criterion, score in zip(rubric, note["scores"], strict=True):
                markdown.append(f"| {criterion.replace('|', '/')} | {score if score is not None else 'N/A'} |")
            markdown.extend(["", "Bằng chứng:", "", *[f"> {q}" for q in note["evidence"]], "",
                note["notes"], "", "<details><summary>Câu trả lời đầy đủ</summary>", "",
                case["answer"], "", "</details>", ""])
        if not args.allow_partial and (report["status"] != "completed"
                or len(rows) != report["summary"]["selected"]):
            raise ValueError(f"Unfinished live run: {track}")
        summary = {"reviewed": len(rows), "selected": report["summary"]["selected"],
            "automated_passes": sum(row["automated_pass"] for row in rows),
            **{v: sum(row["ai_semantic_review"]["verdict"] == v for row in rows)
                for v in ("pass", "partial", "fail")},
            "human_review_status": "pending", "combined_track_score": None}
        result = {"track": track, "source_report": raw_path.name,
            "source_sha256": hashlib.sha256(raw_path.read_bytes()).hexdigest(),
            "summary": summary, "cases": rows}
        (args.run_dir / f"{track}.reviewed.json").write_text(
            json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
        (args.run_dir / f"{track}.reviewed.md").write_text("\n".join(markdown), encoding="utf-8")
        print(track, summary)
    if not args.allow_partial and set(by_id) != known:
        raise ValueError("Review IDs do not match live cases")


if __name__ == "__main__":
    main()
